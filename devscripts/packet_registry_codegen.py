#!/usr/bin/env python3
# 2026-11-14
# purpose
# Generate the packet hotness registry from packets.h plus the reviewed
# config/hot-reload/packet-schema.json overrides.
#
# The generated header is the single source for which packet types the DLL
# handles on the server and client paths. Adding or moving a packet is a schema
# edit plus regeneration, never a hand-maintained switch.
#
#   python devscripts/packet_registry_codegen.py
#   python devscripts/packet_registry_codegen.py --check

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SCHEMA = "config/hot-reload/packet-schema.json"
DEFAULT_PACKETS = "src/network/packets.h"
DEFAULT_HEADER = "src/host/generated/packet-registry-v1.h"
DEFAULT_LEDGER = "config/hot-reload/packet-ledger.json"

ENUM_RE = re.compile(r"^\s*(PACKET_[A-Z0-9_]+)\s*=\s*(\d+)\s*,\s*$")
PATHS = {"resident": "Resident", "dll": "Dll"}


def fail(message: str) -> None:
    print(f"[PACKET CODEGEN] ERROR {message}", file=sys.stderr)


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def parse_packets(path: Path) -> list[dict]:
    entries: list[dict] = []
    in_enum = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if "enum PacketType" in line:
            in_enum = True
            continue
        if in_enum and line.strip().startswith("};"):
            break
        if not in_enum:
            continue
        match = ENUM_RE.match(line)
        if match:
            entries.append({"name": match.group(1), "id": int(match.group(2))})
    return entries


def validate(packets: list[dict], schema: dict) -> list[str]:
    errors: list[str] = []
    if schema.get("schema_version") != 1:
        errors.append(f"unsupported schema_version: {schema.get('schema_version')}")
    if not isinstance(schema.get("protocol_version"), int):
        errors.append("protocol_version must be an integer")
    if not packets:
        errors.append("no PACKET_* entries found in packets.h")
    ids = [item["id"] for item in packets]
    if len(ids) != len(set(ids)):
        errors.append("duplicate packet ids in packets.h")
    names = {item["name"] for item in packets}
    defaults = schema.get("defaults", {})
    for key in ("server", "client"):
        if defaults.get(key, "resident") not in PATHS:
            errors.append(f"defaults.{key} must be resident or dll")
    seen: set[str] = set()
    for override in schema.get("overrides", []):
        name = override.get("type")
        if name not in names:
            errors.append(f"override references unknown packet: {name}")
        if name in seen:
            errors.append(f"duplicate override: {name}")
        seen.add(name)
        for key in ("server", "client"):
            if key in override and override[key] not in PATHS:
                errors.append(f"{name}.{key} must be resident or dll")
    return errors


def generate(packets: list[dict], schema: dict) -> tuple[str, str]:
    defaults = schema.get("defaults", {})
    overrides = {item["type"]: item for item in schema.get("overrides", [])}
    rows: list[dict] = []
    for packet in sorted(packets, key=lambda item: item["id"]):
        override = overrides.get(packet["name"], {})
        server = override.get("server", defaults.get("server", "resident"))
        client = override.get("client", defaults.get("client", "resident"))
        rows.append({
            "id": packet["id"],
            "name": packet["name"],
            "server": server,
            "client": client,
        })

    schema_sha = hashlib.sha256(
        json.dumps(schema, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()
    lines = [
        "// Generated by devscripts/packet_registry_codegen.py.",
        "// Source: src/network/packets.h + config/hot-reload/packet-schema.json",
        "// Do not hand edit. Edit the schema and regenerate.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace mimita::host::packet_registry {",
        "",
        f"inline constexpr std::uint16_t kProtocolVersion = {schema['protocol_version']};",
        "",
        "enum class Path : std::uint8_t { Resident = 0, Dll = 1 };",
        "",
        "struct Entry {",
        "    std::uint16_t id;",
        "    const char* name;",
        "    Path server;",
        "    Path client;",
        "};",
        "",
        "inline constexpr Entry kEntries[] = {",
    ]
    for row in rows:
        lines.append(
            f'    {{{row["id"]}, "{row["name"]}", '
            f'Path::{PATHS[row["server"]]}, Path::{PATHS[row["client"]]}}},')
    lines.extend([
        "};",
        f"inline constexpr std::size_t kEntryCount = {len(rows)};",
        "",
        "inline const Entry* find(std::uint16_t id) {",
        "    for (const Entry& entry : kEntries) {",
        "        if (entry.id == id) {",
        "            return &entry;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "inline Path serverPath(std::uint16_t id) {",
        "    const Entry* entry = find(id);",
        "    return entry ? entry->server : Path::Resident;",
        "}",
        "",
        "inline Path clientPath(std::uint16_t id) {",
        "    const Entry* entry = find(id);",
        "    return entry ? entry->client : Path::Resident;",
        "}",
        "",
        "}  // namespace mimita::host::packet_registry",
        "",
    ])
    header = "\n".join(lines)

    ledger = {
        "schema_version": schema["schema_version"],
        "protocol_version": schema["protocol_version"],
        "generator": "devscripts/packet_registry_codegen.py",
        "generator_version": 1,
        "schema_sha256": schema_sha,
        "header": DEFAULT_HEADER,
        "counts": {
            "total": len(rows),
            "server_dll": sum(1 for row in rows if row["server"] == "dll"),
            "client_dll": sum(1 for row in rows if row["client"] == "dll"),
        },
        "packets": rows,
    }
    ledger_text = json.dumps(ledger, indent=2, sort_keys=True) + "\n"
    return header, ledger_text


def resolve(path: str) -> Path:
    value = Path(path)
    return value if value.is_absolute() else ROOT / value


def write_if_changed(path: Path, text: str) -> bool:
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    path.write_text(text, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the packet hotness registry")
    parser.add_argument("--schema", default=DEFAULT_SCHEMA)
    parser.add_argument("--packets", default=DEFAULT_PACKETS)
    parser.add_argument("--header", default=DEFAULT_HEADER)
    parser.add_argument("--ledger", default=DEFAULT_LEDGER)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    try:
        schema = read_json(resolve(args.schema))
        packets = parse_packets(resolve(args.packets))
    except (OSError, json.JSONDecodeError) as error:
        fail(f"cannot read input: {error}")
        return 2
    errors = validate(packets, schema)
    if errors:
        for error in errors:
            fail(error)
        return 2

    header, ledger_text = generate(packets, schema)
    header_path = resolve(args.header)
    ledger_path = resolve(args.ledger)
    header_path.parent.mkdir(parents=True, exist_ok=True)
    ledger_path.parent.mkdir(parents=True, exist_ok=True)

    if args.check:
        stale: list[str] = []
        for path, expected in ((header_path, header), (ledger_path, ledger_text)):
            try:
                current = path.read_text(encoding="utf-8")
            except OSError:
                stale.append(f"missing {path.relative_to(ROOT)}")
                continue
            if current != expected:
                stale.append(f"stale {path.relative_to(ROOT)}")
        if stale:
            for item in stale:
                fail(item)
            fail("run: python devscripts/packet_registry_codegen.py")
            return 1
        print(f"[PACKET CODEGEN] ok packets={len(packets)} header={args.header}")
        return 0

    wrote_header = write_if_changed(header_path, header)
    wrote_ledger = write_if_changed(ledger_path, ledger_text)
    changed = "wrote" if (wrote_header or wrote_ledger) else "unchanged"
    print(f"[PACKET CODEGEN] {changed} packets={len(packets)} "
          f"header={args.header} ledger={args.ledger}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
