"""Validate hot-reload work plans and generate ownership/claim views.

The JSON plan file is the only hand-maintained plan input. Exact paths always
come from the repository file list and build/source-manifest.json.
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLANS_PATH = ROOT / "docs" / "handoffs" / "hot-reload-work-plans.json"
MANIFEST_PATH = ROOT / "build" / "source-manifest.json"
OUT = ROOT / "docs" / "handoffs"
OWNERS = {"agent-a", "agent-b", "agent-c", "integrator"}
SHARED = ("src/host/abi/", "docs/specs/hotreload/", "docs/handoffs/",
          "config/source-owners.json", "AGENTS.md")


def norm(text: str) -> str:
    return text.replace("\\", "/").lstrip("./")


def files() -> list[str]:
    try:
        raw = subprocess.check_output(
            ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            cwd=ROOT,
        )
        return sorted({norm(item) for item in raw.decode("utf-8").split("\0") if item})
    except (OSError, subprocess.CalledProcessError):
        skip = {".git", "build", "logs", ".dev", "external"}
        return sorted(
            item.relative_to(ROOT).as_posix()
            for item in ROOT.rglob("*")
            if item.is_file() and not any(part in skip for part in item.relative_to(ROOT).parts)
        )


def expand(pattern: str, paths: list[str]) -> set[str]:
    pattern = norm(pattern)
    if pattern.endswith("/**"):
        prefix = pattern[:-3] + "/"
        return {path for path in paths if path.startswith(prefix)}
    if any(ch in pattern for ch in "*?["):
        return {path for path in paths if fnmatch.fnmatchcase(path, pattern)}
    return {pattern} if pattern in paths else set()


def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def validate(plans: dict, paths: list[str]) -> tuple[list[str], list[str], dict[str, set[str]]]:
    errors: list[str] = []
    warnings: list[str] = []
    expanded: dict[str, set[str]] = {}
    seen: set[str] = set()
    if plans.get("schema_version") != 1:
        errors.append("schema_version must be 1")
    for plan in plans.get("plans", []):
        plan_id = str(plan.get("plan_id", "")).strip()
        owner = str(plan.get("owner", ""))
        if not plan_id:
            errors.append("plan missing plan_id")
            continue
        if plan_id in seen:
            errors.append(f"duplicate plan_id: {plan_id}")
        seen.add(plan_id)
        if owner not in OWNERS:
            errors.append(f"{plan_id}: unknown owner {owner!r}")
        matched: set[str] = set()
        for pattern in plan.get("paths", []) or []:
            values = expand(str(pattern), paths)
            if not values:
                warnings.append(f"{plan_id}: no files match {pattern}")
            matched |= values
        expanded[plan_id] = matched
        if owner not in ("agent-a", "integrator"):
            for path in sorted(matched):
                if any(path.startswith(prefix) for prefix in SHARED):
                    errors.append(f"{plan_id}: {owner} claims shared path {path}")
    active = [plan for plan in plans.get("plans", []) if plan.get("status") == "active"]
    for index, left in enumerate(active):
        for right in active[index + 1:]:
            overlap = expanded.get(str(left["plan_id"]), set()) & expanded.get(str(right["plan_id"]), set())
            if overlap:
                sample = ", ".join(sorted(overlap)[:6])
                errors.append(f"active overlap {left['plan_id']} vs {right['plan_id']}: {sample}")
    return errors, warnings, expanded


def write(path: Path, title: str, body: list[str], source: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# {title}\n\n<!-- GENERATED by devscripts/hot_reload_plan_registry.py "
        f"from {source}. Do not edit by hand. -->\n\n" + "\n".join(body).rstrip() + "\n",
        encoding="utf-8",
    )


def generate(plans: dict, manifest: dict, expanded: dict[str, set[str]], warnings: list[str]) -> None:
    rows = ["| Plan | Owner | Status | Files | Objective |", "|---|---|---|---:|---|"]
    for plan in plans.get("plans", []):
        plan_id = str(plan.get("plan_id"))
        rows.append(
            f"| `{plan_id}` | `{plan.get('owner')}` | `{plan.get('status')}` | "
            f"{len(expanded.get(plan_id, set()))} | {plan.get('objective', '')} |"
        )
    rows += ["", "## Active claims"]
    for plan in plans.get("plans", []):
        if plan.get("status") != "active":
            continue
        rows.append(f"\n### `{plan.get('plan_id')}` ({plan.get('owner')})")
        rows.extend(f"- `{path}`" for path in sorted(expanded.get(str(plan.get("plan_id")), set())))
    if warnings:
        rows += ["", "## Warnings"] + [f"- {item}" for item in warnings]
    write(OUT / "hot-reload-work-plans.md", "Hot-reload work plans", rows,
          "docs/handoffs/hot-reload-work-plans.json")

    matrix = ["| Path | Owner | Active plans |", "|---|---|---|"]
    for item in sorted(manifest.get("sources", []), key=lambda value: value.get("path", "")):
        path = norm(str(item.get("path", "")))
        claims = sorted(
            str(plan.get("plan_id"))
            for plan in plans.get("plans", [])
            if path in expanded.get(str(plan.get("plan_id")), set())
        )
        matrix.append(f"| `{path}` | `{item.get('owner', '')}` | "
                      f"{', '.join(f'`{claim}`' for claim in claims) or '-'} |")
    write(OUT / "hot-reload-ownership-matrix.md", "Hot-reload ownership matrix",
          matrix, "build/source-manifest.json + docs/handoffs/hot-reload-work-plans.json")

    claims = ["| Plan | Owner | Claimed paths |", "|---|---|---|"]
    for plan in plans.get("plans", []):
        if plan.get("status") != "active":
            continue
        paths = "<br>".join(f"`{path}`" for path in sorted(expanded.get(str(plan.get('plan_id')), set())))
        claims.append(f"| `{plan.get('plan_id')}` | `{plan.get('owner')}` | {paths or '-'} |")
    claims.append("\nLegacy manual table: `docs/handoffs/hot-reload-agent-claims-20261113.md` (do not add rows).")
    write(OUT / "hot-reload-agent-claims.generated.md", "Generated hot-reload claims",
          claims, "docs/handoffs/hot-reload-work-plans.json")


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate/generate hot-reload work registry")
    parser.add_argument("--check", action="store_true", help="validate without writing")
    parser.add_argument("--json", action="store_true", help="machine-readable summary")
    args = parser.parse_args()
    plans = load(PLANS_PATH)
    manifest = load(MANIFEST_PATH)
    errors, warnings, expanded = validate(plans, files())
    summary = {"plans": len(plans.get("plans", [])),
               "active": sum(1 for p in plans.get("plans", []) if p.get("status") == "active"),
               "errors": errors, "warnings": warnings}
    if args.json:
        print(json.dumps(summary, indent=2))
    else:
        print(f"[PLAN REGISTRY] plans={summary['plans']} active={summary['active']} "
              f"errors={len(errors)} warnings={len(warnings)}")
        for item in errors:
            print(f"[PLAN REGISTRY] ERROR {item}", file=sys.stderr)
        for item in warnings:
            print(f"[PLAN REGISTRY] WARN {item}", file=sys.stderr)
    if errors:
        return 1
    if not args.check:
        generate(plans, manifest, expanded, warnings)
        print("[PLAN REGISTRY] generated ownership, work-plan, and claim views")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
